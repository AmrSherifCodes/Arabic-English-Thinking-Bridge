export interface VoiceGradeResult {
  passed: boolean;
  score: number; // 0..100
  xpEarned: number;
  bestExpectedPhrase: string;
  matchedChoiceIndex: number;
  feedbackAr: string;
  feedbackEn: string;
}

export const TRAVEL_SCENARIOS_STORAGE_KEY = 'tb.travelScenariosCompleted.v10_3';

export function resolveScenarioLang(targetLang: TargetLanguage | string): ScenarioLang {
  const base = (targetLang || 'en').toLowerCase().split(/[-_]/)[0];
  if (base === 'de' || base === 'es' || base === 'it' || base === 'fr' || base === 'ar') {
    return base;
  }
  return 'en';
}

export function loadCompletedTravelScenarios(): string[] {
  try {
    if (typeof localStorage === 'undefined') return [];
    const raw = localStorage.getItem(TRAVEL_SCENARIOS_STORAGE_KEY);
    if (!raw) return [];
    const parsed = JSON.parse(raw);
    return Array.isArray(parsed) ? parsed.filter((x): x is string => typeof x === 'string') : [];
  } catch {
    return [];
  }
}

export function markTravelScenarioCompleted(scenarioId: string): string[] {
  const current = loadCompletedTravelScenarios();
  if (current.includes(scenarioId)) return current;
  const next = [...current, scenarioId];
  try {
    if (typeof localStorage !== 'undefined') {
      localStorage.setItem(TRAVEL_SCENARIOS_STORAGE_KEY, JSON.stringify(next));
    }
  } catch {}
  return next;
}

/**
 * On-device voice-reply fuzzy grader using normalized Levenshtein + token similarity.
 * >= 65% = natural pass (+20 XP); < 65% = gentle coaching hint showing the exact phrase to repeat.
 */
export function gradeVoiceReply(spoken: string, expectedPhrases: string[]): VoiceGradeResult {
  const cleanSpoken = spoken.trim();
  const safeExpected = expectedPhrases.filter((p) => p && p.trim().length > 0);
  if (!cleanSpoken || safeExpected.length === 0) {
    return {
      passed: false,
      score: 0,
      xpEarned: 0,
      bestExpectedPhrase: safeExpected[0] || '',
      matchedChoiceIndex: 0,
      feedbackAr: `لم نلتقط صوتك بوضوح — جرّب تقول: "${safeExpected[0] || ''}"`,
      feedbackEn: `We didn't catch that — try saying: "${safeExpected[0] || ''}"`,
    };
  }

  let bestScore = 0;
  let bestIdx = 0;
  for (let i = 0; i < safeExpected.length; i += 1) {
    const sim = computePhraseSimilarity(cleanSpoken, safeExpected[i]);
    if (sim > bestScore) {
      bestScore = sim;
      bestIdx = i;
    }
  }

  const pct = Math.round(bestScore * 100);
  const bestPhrase = safeExpected[bestIdx];

  if (pct >= 65) {
    return {
      passed: true,
      score: pct,
      xpEarned: 20,
      bestExpectedPhrase: bestPhrase,
      matchedChoiceIndex: bestIdx,
      feedbackAr: `ممتاز! نطق طبيعي (${pct}%) · +20 XP 🎉`,
      feedbackEn: `Awesome! Natural reply (${pct}%) · +20 XP 🎉`,
    };
  }

  return {
    passed: false,
    score: pct,
    xpEarned: 0,
    bestExpectedPhrase: bestPhrase,
    matchedChoiceIndex: bestIdx,
    feedbackAr: `قريب جداً (${pct}%)! جرّب تعيد الجملة دي: "${bestPhrase}"`,
    feedbackEn: `Almost there (${pct}%)! Try repeating: "${bestPhrase}"`,
  };
}

